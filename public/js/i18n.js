const LANGUAGE_STORAGE_KEYS = ["kwanlong_lang", "app_lang"];
let initPromise = null;

function normalizeLang(lang) {
  const value = String(lang || "").toLowerCase();
  if (value === "la") return "lo";
  if (value === "th" || value === "lo" || value === "en") return value;
  return "th";
}

function getSavedLanguage() {
  return normalizeLang(localStorage.getItem("kwanlong_lang") || localStorage.getItem("app_lang") || "th");
}

function persistLanguage(lang) {
  const normalized = normalizeLang(lang);
  LANGUAGE_STORAGE_KEYS.forEach(key => localStorage.setItem(key, normalized));
  return normalized;
}

function updateContent() {
  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.getAttribute("data-i18n");
    const translated = i18next.t(key);
    if (translated && translated !== key) element.textContent = translated;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    const key = element.getAttribute("data-i18n-placeholder");
    const translated = i18next.t(key);
    if (translated && translated !== key) element.setAttribute("placeholder", translated);
  });

  document.documentElement.lang = normalizeLang(i18next.language);
}

function syncLanguageSelects(lang) {
  document.querySelectorAll("[data-language-select], #langSelect, #languageSelect").forEach(select => {
    if (select && "value" in select) select.value = normalizeLang(lang);
  });
}

async function init(lang = getSavedLanguage()) {
  const selectedLang = persistLanguage(lang);

  if (!window.i18next) {
    syncLanguageSelects(selectedLang);
    return selectedLang;
  }

  if (i18next.isInitialized) {
    await i18next.changeLanguage(selectedLang);
  } else {
    initPromise = initPromise || i18next.init({
      lng: selectedLang,
      fallbackLng: "en",
      resources
    });
    await initPromise;
    await i18next.changeLanguage(selectedLang);
  }

  updateContent();
  syncLanguageSelects(selectedLang);
  return selectedLang;
}

function initLanguageToggle() {
  document.querySelectorAll("[data-language-select], #langSelect, #languageSelect").forEach(select => {
    if (select.dataset.i18nBound === "true") return;
    select.dataset.i18nBound = "true";
    select.addEventListener("change", async event => {
      await init(event.target.value);
    });
  });
  syncLanguageSelects(getSavedLanguage());
}

window.KwanLongI18n = {
  init,
  initLanguageToggle,
  updateContent,
  t: key => (window.i18next ? i18next.t(key) : key),
  getLanguage: getSavedLanguage,
  setLanguage: init,
  resources
};

document.addEventListener("DOMContentLoaded", async () => {
  await init();
  initLanguageToggle();
});
